#!/usr/bin/env python3
"""Writes hifi/fft_tw.h: the pre- and post-rotations of the IMDCT through an N/4-point complex
FFT (ETUDE §74), w[m] = exp(-2 i pi (m + 1/8) / N), m < N/4, as Q31 {cos, sin} pairs, for the
Vorbis block sizes 256 and 2048 (FFT of 64 and 512 points on HIFIACC).
    mkfft_tw.py > hifi/fft_tw.h
"""
import math

print("/* Generated by tools/mkfft_tw.py: IMDCT rotations w[m] = exp(-2 i pi (m + 1/8) / N), Q31")
print(" * {cos, sin} pairs, m < N/4 (ETUDE §74) */")
for n in (256, 2048):
    print("static const int32_t fft_tw%d[%d][2] = {" % (n, n // 4))
    row = []
    for m in range(n // 4):
        a = 2 * math.pi * (m + 0.125) / n
        row.append("{%d, %d}" % tuple(min(round(v * 2 ** 31), 2 ** 31 - 1) for v in (math.cos(a), math.sin(a))))
    for i in range(0, len(row), 4):
        print("    " + ", ".join(row[i:i + 4]) + ",")
    print("};")
