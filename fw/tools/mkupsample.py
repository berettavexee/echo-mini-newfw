#!/usr/bin/env python3
"""Polyphase interpolation filters for core B's upsampler (hifi/rt.c, ETUDE §59): windowed-sinc
low-pass (Kaiser, beta 8), cutoff at 0.48 of the input rate (-0.1 dB up to 0.4, -82 dB from 0.6), T taps per phase, Q14, for factors L = 2,
3, 4 and 6. Coefficient h[p + k * L] weighs input x[n - k] for output phase p (output n * L + p).
  mkupsample.py hifi/upsample_tab.h"""
import math, sys
T = 24                                   # taps per phase
def i0(x):
    s = t = 1.0
    for k in range(1, 40):
        t *= (x / (2 * k)) ** 2
        s += t
    return s
def table(L, beta=8.0):
    n = T * L - 1                        # odd: a whole number of samples of delay, (n - 1) / 2
    fc = 0.48 / L                        # of the output rate
    h = []
    for j in range(n):
        x = j - (n - 1) / 2
        s = 2 * fc * (math.sin(2 * math.pi * fc * x) / (2 * math.pi * fc * x) if x else 1.0)
        w = i0(beta * math.sqrt(1 - (2 * j / (n - 1) - 1) ** 2)) / i0(beta)
        h.append(s * w * L)              # gain L: each phase sums to about 1
    q = [int(round(v * 16384)) for v in h] + [0]     # T * L entries, the last one zero
    for p in range(L):                   # each phase sums exactly to 1.0 (Q14): no DC ripple
        idx = list(range(p, n, L))       # (the zero entry left out)
        q[idx[len(idx) // 2]] += 16384 - sum(q[i] for i in idx)
    return q
out = ["/* Generated by tools/mkupsample.py: polyphase interpolation filters (Q14), %d taps per phase */" % T,
       "#define UP_TAPS %d" % T]
for L in (2, 3, 4, 6):
    q = table(L)
    out.append("static const int16_t up_h%d[%d] = {" % (L, len(q)))
    for i in range(0, len(q), 12):
        out.append("    " + ", ".join(str(v) for v in q[i:i + 12]) + ",")
    out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
